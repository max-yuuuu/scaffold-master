package com.scaffold.lowcode.workspace;

/**
 * 底座升级里一个文件的三方合并结论（方案 §5.2「把平台改的那几行与项目改的那几行分开」）。
 *
 * <p>判据只有一条：<b>平台永远不静默删掉项目里有的东西，也永远不把没编译过的内容写进别人的仓库</b>。
 * 所以只有 {@link #CLEAN} 会被写进升级分支，其余都只出现在清单里等人处理 ——
 * 与合并请求「冲突只列文件、不在网页里改代码」是同一口径。
 */
public enum MergeOutcome {

    /** 可以自动合：{@code content} 就是合并后的文本，写进升级分支 */
    CLEAN,

    /** 不需要写：项目侧与合并结果一致（平台没改，或两侧都删了） */
    UNCHANGED,

    /** 真冲突：两侧改了同一行，或项目删了而平台改了。内容不给，交人解 */
    CONFLICT,

    /** 底座快照不再交付这个文件，而项目里还有：删不删由人决定，平台不代删 */
    DROPPED_BY_PLATFORM,

    /** 读不出文本（含空字节或非 UTF-8）：A 档里没有二进制文件该被自动搬，出现就说明现场不对 */
    BINARY
}
